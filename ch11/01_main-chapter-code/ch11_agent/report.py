"""IncidentReport schema (strict structured output), ranking, and Markdown postmortem rendering."""

from __future__ import annotations

from datetime import UTC, datetime
from typing import Any

from pydantic import BaseModel


class Hypothesis(BaseModel):
    hypothesis: str
    evidence: list[str]
    confidence: float  # 0..1


class IncidentReport(BaseModel):
    summary: str
    impact: str
    timeline: list[str]
    hypotheses: list[Hypothesis]
    next_actions: list[str]


def strict_schema(model: type[BaseModel]) -> dict[str, Any]:
    """Pydantic JSON schema -> the subset strict structured outputs accept.

    Every object gets additionalProperties=false and all properties required; `title` and
    `default` keys are dropped.
    """
    def fix(node: Any) -> Any:
        if isinstance(node, dict):
            node = {k: fix(v) for k, v in node.items() if k not in ("title", "default")}
            if node.get("type") == "object" and "properties" in node:
                node["additionalProperties"] = False
                node["required"] = list(node["properties"])
        elif isinstance(node, list):
            node = [fix(v) for v in node]
        return node

    return fix(model.model_json_schema())


def response_format(model: type[BaseModel] = IncidentReport) -> dict[str, Any]:
    return {"type": "json_schema",
            "json_schema": {"name": model.__name__, "strict": True, "schema": strict_schema(model)}}


def ranked(report: IncidentReport) -> list[Hypothesis]:
    """Hypotheses by confidence, highest first (ties keep the model's order)."""
    clamp = [h.model_copy(update={"confidence": min(max(h.confidence, 0.0), 1.0)})
             for h in report.hypotheses]
    return sorted(clamp, key=lambda h: -h.confidence)


def render_markdown(report: IncidentReport, *, alert: str, model: str, steps: int,
                    cost_usd: float, generated_at: datetime | None = None) -> str:
    at = (generated_at or datetime.now(UTC)).strftime("%Y-%m-%d %H:%M UTC")
    out = [
        "# Incident report (draft, generated by an AI agent)",
        "",
        (f"*Generated {at} by `{model}` in {steps} tool steps, cost ${cost_usd:.4f}. "
         "A human must review it before it is shared.*"),
        "",
        f"**Alert:** {alert}",
        "",
        "## Summary", "", report.summary, "",
        "## Impact", "", report.impact, "",
        "## Timeline (UTC)", "",
        *[f"- {t}" for t in report.timeline], "",
        "## Hypotheses, most likely first", "",
    ]
    for i, h in enumerate(ranked(report), 1):
        out += [f"### {i}. {h.hypothesis} (confidence {h.confidence:.0%})", ""]
        out += [f"- {e}" for e in h.evidence] + [""]
    out += ["## Proposed next actions (a human decides and executes these)", ""]
    out += [f"{i}. {a}" for i, a in enumerate(report.next_actions, 1)]
    return "\n".join(out) + "\n"
